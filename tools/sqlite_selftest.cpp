void CaseParsesHeader() {
    Database db;
    if (!OpenFixture(db)) return;
    if (db.pageSize() != 4096) {
        selftest::Emit(L"sqlite_parses_header", false,
            (L"页大小应为 4096，实际 " + std::to_wstring(db.pageSize())).c_str());
        return;
    }
    if (db.textEncoding() != 1) {
        selftest::Emit(L"sqlite_parses_header", false,
            (L"文本编码应为 1(UTF-8)，实际 " + std::to_wstring(db.textEncoding())).c_str());
        return;
    }
    // 非 SQLite：必须明确失败（不是静默给空结果）
    {
        Database bad;
        std::string e;
        std::vector<uint8_t> garbage(200, 0x41);
        if (bad.LoadFromMemory(garbage, e) || e.empty()) {
            selftest::Emit(L"sqlite_parses_header", false,
                L"全 0x41 的字节不是 SQLite，必须失败**且**给出可读 err");
            return;
        }
    }
    // 太短
    {
        Database tiny;
        std::string e;
        std::vector<uint8_t> t(10, 0x00);
        if (tiny.LoadFromMemory(t, e) || e.empty()) {
            selftest::Emit(L"sqlite_parses_header", false,
                L"10 字节输入必须失败且给出可读 err");
            return;
        }
    }
    selftest::Emit(L"sqlite_parses_header", true,
        (L"页大小 4096 / UTF-8 / 页数 " + std::to_wstring(db.pageCount())
            + L"；非 SQLite 与过短输入均明确报错").c_str());
}

void CaseListsTablesAndColumns() {
    Database db;
    if (!OpenFixture(db)) return;
    if (!db.HasTable("urls")) {
        selftest::Emit(L"sqlite_lists_tables_and_columns", false, L"应存在表 urls");
        return;
    }
    if (db.HasTable("nope")) {
        selftest::Emit(L"sqlite_lists_tables_and_columns", false, L"不该存在表 nope");
        return;
    }
    const std::vector<std::string> want = {
        "id", "url", "title", "visit_count", "last_visit_time", "hidden" };
    std::vector<std::string> got;
    if (!db.TableColumns("urls", got)) {
        selftest::Emit(L"sqlite_lists_tables_and_columns", false, L"取 urls 列名失败");
        return;
    }
    if (got.size() != want.size()) {
        selftest::Emit(L"sqlite_lists_tables_and_columns", false,
            (L"列数应为 " + std::to_wstring(want.size()) + L"，实际 "
                + std::to_wstring(got.size())).c_str());
        return;
    }
    for (size_t i = 0; i < want.size(); ++i) {
        if (got[i] != want[i]) {
            selftest::Emit(L"sqlite_lists_tables_and_columns", false,
                (L"第 " + std::to_wstring(i) + L" 列应为「" + W(want[i]) + L"」，实际「"
                    + W(got[i]) + L"」").c_str());
            return;
        }
    }
    selftest::Emit(L"sqlite_lists_tables_and_columns", true,
        L"urls 存在且有 6 列，列名与顺序均与 CREATE TABLE 一致");
}

void CaseDecodesAllSerialTypes() {
    Database db;
    if (!OpenFixture(db)) return;
    std::vector<Row> rows;
    std::string err;
    if (!db.ScanTable("urls", "", true, 0, rows, err)) {
        selftest::Emit(L"sqlite_decodes_all_serial_types", false,
            (L"全表扫描失败：" + W(err)).c_str());
        return;
    }
    if (rows.size() != 6) {
        selftest::Emit(L"sqlite_decodes_all_serial_types", false,
            (L"应有 6 行，实际 " + std::to_wstring(rows.size())).c_str());
        return;
    }
    bool sawNull = false, saw300 = false, sawCommaQuote = false;
    for (const auto& r : rows) {
        if (r.size() < 6) {
            selftest::Emit(L"sqlite_decodes_all_serial_types", false,
                (L"每行应有 6 列，实际 " + std::to_wstring(r.size())).c_str());
            return;
        }
        if (r[3].kind != Value::Kind::Integer) {
            selftest::Emit(L"sqlite_decodes_all_serial_types", false,
                L"visit_count 应为整数类型（不是文本）");
            return;
        }
        if (r[1].IsNull() && r[2].IsNull()) sawNull = true;
        if (r[2].kind == Value::Kind::Text && r[2].text.size() == 300) {
            saw300 = true;
            for (char c : r[2].text) {
                if (c != 'x') {
                    selftest::Emit(L"sqlite_decodes_all_serial_types", false,
                        L"300 字符的长标题内容不该含 'x' 以外的字符（跨页拼接错位）");
                    return;
                }
            }
        }
        if (r[2].kind == Value::Kind::Text
            && r[2].text.find("逗号") != std::string::npos
            && r[2].text.find('"') != std::string::npos) {
            sawCommaQuote = true;
        }
    }
    if (!sawNull) {
        selftest::Emit(L"sqlite_decodes_all_serial_types", false,
            L"没找到 url/title 为 NULL 的那行（NULL 解码错）");
        return;
    }
    if (!saw300) {
        selftest::Emit(L"sqlite_decodes_all_serial_types", false,
            L"没找到 300 字符的长标题（长文本/跨页解码错）");
        return;
    }
    if (!sawCommaQuote) {
        selftest::Emit(L"sqlite_decodes_all_serial_types", false,
            L"没找到含逗号与引号的标题（文本边界错）");
        return;
    }
    selftest::Emit(L"sqlite_decodes_all_serial_types", true,
        L"6 行全部解出：NULL 保留为 NULL、整数是整数、含逗号引号的文本与 300 字符长文本均完整");
}

void CaseOrdersAndLimits() {
    Database db;
    if (!OpenFixture(db)) return;
    std::vector<Row> rows;
    std::string err;
    // 期望（官方 sqlite3：ORDER BY last_visit_time DESC LIMIT 3）
    //   1) 「最后一条」   https://example.com/f   t=13300000000000099
    //   2) 「倒数第三条」 https://example.com/e   t=13300000000000005
    //   3) 'x'*300        https://example.com/d   t=13300000000000003
    if (!db.ScanTable("urls", "last_visit_time", false, 3, rows, err)) {
        selftest::Emit(L"sqlite_orders_and_limits", false,
            (L"降序取 3 条失败：" + W(err)).c_str());
        return;
    }
    if (rows.size() != 3) {
        selftest::Emit(L"sqlite_orders_and_limits", false,
            (L"应取到 3 条，实际 " + std::to_wstring(rows.size())).c_str());
        return;
    }
    struct Want { const char* url; const char* title; long long t; };
    const Want want[3] = {
        { "https://example.com/f", "最后一条", 13300000000000099LL },
        { "https://example.com/e", "倒数第三条", 13300000000000005LL },
        { "https://example.com/d", nullptr, 13300000000000003LL },
    };
    for (int i = 0; i < 3; ++i) {
        if (rows[i][1].AsText() != want[i].url) {
            selftest::Emit(L"sqlite_orders_and_limits", false,
                (L"第 " + std::to_wstring(i + 1) + L" 条 url 应为「" + W(want[i].url)
                    + L"」，实际「" + W(rows[i][1].AsText()) + L"」").c_str());
            return;
        }
        if (rows[i][4].AsInt() != want[i].t) {
            selftest::Emit(L"sqlite_orders_and_limits", false,
                (L"第 " + std::to_wstring(i + 1) + L" 条 last_visit_time 应为 "
                    + std::to_wstring(want[i].t) + L"，实际 "
                    + std::to_wstring(rows[i][4].AsInt())).c_str());
            return;
        }
        if (want[i].title && rows[i][2].AsText() != want[i].title) {
            selftest::Emit(L"sqlite_orders_and_limits", false,
                (L"第 " + std::to_wstring(i + 1) + L" 条标题应为「" + W(want[i].title)
                    + L"」，实际「" + W(rows[i][2].AsText()) + L"」").c_str());
            return;
        }
    }
    selftest::Emit(L"sqlite_orders_and_limits", true,
        L"降序前 3 条的 url / 标题 / 时间戳全部与官方 sqlite3 一致");
}

void CaseAscendingOrder() {
    Database db;
    if (!OpenFixture(db)) return;
    std::vector<Row> rows;
    std::string err;
    // 期望（官方：ORDER BY last_visit_time ASC LIMIT 2）=> t=...000 然后 t=...001
    // ⚠ t=...001 那行的 url/title 是 NULL ⇒ 同时钉住「NULL 不因为排序被挤到头部」
    if (!db.ScanTable("urls", "last_visit_time", true, 2, rows, err)) {
        selftest::Emit(L"sqlite_ascending_order", false,
            (L"升序取 2 条失败：" + W(err)).c_str());
        return;
    }
    if (rows.size() != 2) {
        selftest::Emit(L"sqlite_ascending_order", false,
            (L"应取到 2 条，实际 " + std::to_wstring(rows.size())).c_str());
        return;
    }
    if (rows[0][4].AsInt() != 13300000000000000LL) {
        selftest::Emit(L"sqlite_ascending_order", false,
            (L"升序第 1 条应为 ...000，实际 " + std::to_wstring(rows[0][4].AsInt())).c_str());
        return;
    }
    if (rows[1][4].AsInt() != 13300000000000001LL) {
        selftest::Emit(L"sqlite_ascending_order", false,
            (L"升序第 2 条应为 ...001（该行 url/title 为 NULL），实际 "
                + std::to_wstring(rows[1][4].AsInt())).c_str());
        return;
    }
    selftest::Emit(L"sqlite_ascending_order", true,
        L"升序前 2 条时间戳正确，NULL 行没有被挤到头部");
}

void CaseSelectColumns() {
    Database db;
    if (!OpenFixture(db)) return;
    std::vector<Row> rows;
    std::string err;
    // 列序必须按**请求顺序**（title 在前），不是 schema 顺序
    if (!db.SelectColumns("urls", { "title", "url" }, 2, rows, err)) {
        selftest::Emit(L"sqlite_select_columns", false, (L"选列失败：" + W(err)).c_str());
        return;
    }
    if (rows.size() != 2 || rows[0].size() != 2) {
        selftest::Emit(L"sqlite_select_columns", false, L"应取 2 行 × 2 列");
        return;
    }
    if (rows[0][0].AsText() != "标题 A") {
        selftest::Emit(L"sqlite_select_columns", false,
            (L"第 1 行第 1 列应为「标题 A」（列序按请求），实际「"
                + W(rows[0][0].AsText()) + L"」").c_str());
        return;
    }
    if (rows[0][1].AsText() != "https://example.com/a") {
        selftest::Emit(L"sqlite_select_columns", false, L"第 1 行第 2 列应为 .../a");
        return;
    }
    // 缺列：整体仍成功（少一列不该让整次读取白费），但必须给出明确 err
    std::vector<Row> rows2;
    std::string err2;
    if (!db.SelectColumns("urls", { "title", "no_such_col" }, 1, rows2, err2)) {
        selftest::Emit(L"sqlite_select_columns", false, L"含不存在列时不该整体失败");
        return;
    }
    if (err2.empty()) {
        selftest::Emit(L"sqlite_select_columns", false, L"含不存在列时必须给出明确 err");
        return;
    }
    if (rows2.empty() || rows2[0].size() != 2 || !rows2[0][1].IsNull()) {
        selftest::Emit(L"sqlite_select_columns", false,
            L"缺列应回 2 列且缺的那列给 NULL 值");
        return;
    }
    selftest::Emit(L"sqlite_select_columns", true,
        L"列序按请求；缺列不整体失败，但给明确 err 且该列给 NULL");
}

void CaseRejectsGarbage() {
    // WAL 模式（write/read version = 2）：**必须拒绝**。
    // WAL 模式下主库文件**不完整**（最新数据在 -wal 里），读它会给
    // 「看着对但缺最新数据」的结果 —— 这比报错危险得多。
    {
        std::vector<uint8_t> b = Fixture();
        b[18] = 2;
        b[19] = 2;
        Database db;
        std::string err;
        if (db.LoadFromMemory(b, err)) {
            selftest::Emit(L"sqlite_rejects_garbage", false,
                L"WAL 模式库必须拒绝（主库文件不完整）");
            return;
        }
        if (W(err).find(L"WAL") == std::wstring::npos) {
            selftest::Emit(L"sqlite_rejects_garbage", false,
                (L"WAL 拒绝原因里应提到 WAL，实际：" + W(err)).c_str());
            return;
        }
    }
    // 页大小非法（3 不是 2 的幂）
    {
        std::vector<uint8_t> b = Fixture();
        b[16] = 0;
        b[17] = 3;
        Database db;
        std::string err;
        if (db.LoadFromMemory(b, err) || err.empty()) {
            selftest::Emit(L"sqlite_rejects_garbage", false, L"页大小 3 必须拒绝");
            return;
        }
    }
    // 表不存在 / 排序列不存在
    {
        Database db;
        if (!OpenFixture(db)) return;
        std::vector<Row> rows;
        std::string err;
        if (db.ScanTable("nope", "", true, 0, rows, err)) {
            selftest::Emit(L"sqlite_rejects_garbage", false, L"扫不存在的表必须失败");
            return;
        }
        // 错误里要带现有表清单 —— 让模型能自我纠正，而不是只收到「失败」
        if (W(err).find(L"urls") == std::wstring::npos) {
            selftest::Emit(L"sqlite_rejects_garbage", false,
                (L"表不存在的错误里应带上现有表清单，实际：" + W(err)).c_str());
            return;
        }
        std::vector<Row> rows2;
        std::string err2;
        if (db.ScanTable("urls", "no_such_col", false, 1, rows2, err2)) {
            selftest::Emit(L"sqlite_rejects_garbage", false, L"按不存在的列排序必须失败");
            return;
        }
    }
    selftest::Emit(L"sqlite_rejects_garbage", true,
        L"空/魔数错/WAL/页大小非法/表不存在/列不存在 均明确报错并说明原因");
}

