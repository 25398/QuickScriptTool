// =============================================================================
// SqliteSelfTest — 只读 SQLite 解析自检（src/sqlite/）
// =============================================================================
// 被测：src/sqlite/sqlite_read.cpp（纯逻辑，只吃字节；不碰 Win32）
//
// 为什么需要它：助手要读**浏览器历史**（Edge/Chrome 的 `History` 是 SQLite）。
// 对照实测的 UI 路线：`observePage` 在 edge:// 内置页必然失败 →
// `listUiControls` 只看到进视口的几十条、标题还被省略号截断 → 模型反复 zoom 读像素
// → 最后用 Excel COM 收尾，**单轮 23.6 秒**。读库是**一条命令、全量、标题完整**。
//
// 而 `sqlite_read.cpp` 是**手写的二进制格式解析器** —— 这类代码「看起来对」和
// 「真对」差得很远：我第一版算错了 record header 与 body 的偏移关系，
// 解出来的字符串整体错位（`table` 读成 `bleme`）。所以这里必须钉死：
//   · 记录解码：serial type 的每一种（NULL / 各宽度整数 / 浮点 / 文本 / 长文本）
//   · 排序 + LIMIT 的语义（浏览器历史就靠它取「最近 N 条」）
//   · 非法输入必须**明确报错**，不许静默给空结果
//
// 夹具来源（可复现）：`build/_tmp/mk_sqlite_fixture.py` 用官方 `sqlite3` 模块造库，
// **期望值同样由官方模块查出** —— 不是照本实现反推的。
//   表 urls(id, url, title, visit_count, last_visit_time, hidden)，6 行：
//     rowid=1  .../a  「标题 A」                     visit_count=5  t=...000
//     rowid=2  .../b  「标题 B 带,逗号和"引号"」                    t=...002
//     rowid=3  NULL   NULL                                        t=...001（钉 NULL）
//     rowid=4  .../d  'x'*300                                     t=...003（钉长文本）
//     rowid=5  .../e  「倒数第三条」                                t=...005
//     rowid=6  .../f  「最后一条」                                  t=...099
//
//   MSBuild ... /t:SqliteSelfTest
//   build\Release\SqliteSelfTest.exe --json
