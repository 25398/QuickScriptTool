/// 打开夹具库；失败直接报断言失败并返回 false。
bool OpenFixture(Database& db) {
    std::string err;
    if (db.LoadFromMemory(Fixture(), err)) return true;
    selftest::Emit(L"sqlite_internal", false,
        (L"夹具库应当能解析，却失败：" + std::wstring(err.begin(), err.end())).c_str());
    return false;
}

std::wstring W(const std::string& s) {
    return std::wstring(s.begin(), s.end());
}

