int wmain(int argc, wchar_t** argv) {
    bool listOnly = false;
    for (int i = 1; i < argc; ++i) {
        const std::wstring a = argv[i] ? argv[i] : L"";
        if (a == L"--json") {
            selftest::gJson = true;
            selftest::InitUtf8Stdout();
        } else if (a == L"--list") {
            listOnly = true;
            selftest::InitUtf8Stdout();
        } else if (a == L"--help" || a == L"-h") {
            selftest::PrintCaseList(L"SqliteSelfTest", kCases,
                sizeof(kCases) / sizeof(kCases[0]));
            return 0;
        }
    }
    if (listOnly) {
        selftest::PrintCaseList(L"SqliteSelfTest", kCases,
            sizeof(kCases) / sizeof(kCases[0]));
        return 0;
    }

    CaseParsesHeader();
    CaseListsTablesAndColumns();
    CaseDecodesAllSerialTypes();
    CaseOrdersAndLimits();
    CaseAscendingOrder();
    CaseSelectColumns();
    CaseRejectsGarbage();

    selftest::EmitSummary();
    return selftest::ExitCode();
}
